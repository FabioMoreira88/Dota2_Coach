-- Notas de 0 a 10 por área (rota, lutas, itens, visão, sobrevivência) de cada comentário de partida.

create table match_area_score (
    id          bigint generated by default as identity primary key,
    comment_id  bigint                   not null references match_review_comment (id),
    account_id  bigint                   not null,
    match_id    bigint                   not null,
    scored_at   timestamp with time zone not null,
    area        varchar(20)              not null,
    score       integer                  not null,
    reason      varchar(500)
);

create index ix_match_area_score_account on match_area_score (account_id, scored_at);
