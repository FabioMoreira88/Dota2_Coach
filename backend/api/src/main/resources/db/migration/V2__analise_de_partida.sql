-- Histórico das análises de partida escolhida e dos comentários do coach.

create table match_review (
    id            bigint generated by default as identity primary key,
    account_id    bigint                   not null,
    match_id      bigint                   not null,
    position      varchar(20),
    analyzed_at   timestamp with time zone not null,
    replay_parsed boolean                  not null,
    metrics_json  text                     not null,
    markdown      text                     not null
);

create index ix_match_review_account on match_review (account_id, analyzed_at);

create table match_review_comment (
    id             bigint generated by default as identity primary key,
    review_id      bigint                   not null references match_review (id),
    provider       varchar(50)              not null,
    model          varchar(100)             not null,
    generated_at   timestamp with time zone not null,
    input_tokens   bigint                   not null,
    output_tokens  bigint                   not null,
    cost_usd       numeric(10, 4)           not null,
    text           text                     not null
);

create index ix_match_review_comment_review on match_review_comment (review_id);
