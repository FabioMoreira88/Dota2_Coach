-- Metas numéricas dos focos de cada diagnóstico, conferidas no próximo Raio-X e nas análises de partida.

create table focus_goal (
    id            bigint generated by default as identity primary key,
    diagnosis_id  bigint           not null references coach_diagnosis (id),
    ordinal       integer          not null,
    title         varchar(200)     not null,
    metric        varchar(40)      not null,
    hero_name     varchar(60),
    baseline      double precision,
    target        double precision not null
);

create index ix_focus_goal_diagnosis on focus_goal (diagnosis_id, ordinal);
