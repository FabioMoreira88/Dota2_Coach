-- Histórico de Raio-X e dos diagnósticos do coach. Base do módulo de evolução.

create table xray_report (
    id            bigint generated by default as identity primary key,
    account_id    bigint                   not null,
    position      varchar(20),
    collected_at  timestamp with time zone not null,
    recent_window integer                  not null,
    metrics_json  text                     not null,
    markdown      text                     not null
);

create index ix_xray_report_account on xray_report (account_id, collected_at);

create table coach_diagnosis (
    id             bigint generated by default as identity primary key,
    report_id      bigint                   not null references xray_report (id),
    provider       varchar(50)              not null,
    model          varchar(100)             not null,
    generated_at   timestamp with time zone not null,
    input_tokens   bigint                   not null,
    output_tokens  bigint                   not null,
    cost_usd       numeric(10, 4)           not null,
    text           text                     not null
);

create index ix_coach_diagnosis_report on coach_diagnosis (report_id);
